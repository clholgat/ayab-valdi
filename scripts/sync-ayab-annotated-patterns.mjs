#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.resolve(process.argv[2] ?? "");
const outputRoot = path.join(
  repoRoot,
  "src/modules/preview/src/patterns/annotated",
);
const manifestPath = path.join(
  repoRoot,
  "src/modules/preview/src/AnnotatedPatternFiles.ts",
);

if (!process.argv[2] || !fs.existsSync(path.join(sourceRoot, ".git"))) {
  console.error("Usage: node scripts/sync-ayab-annotated-patterns.mjs /path/to/ayab-patterns");
  process.exit(1);
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name === ".git") return [];
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(entryPath);
    return /\.png$/i.test(entry.name) ? [entryPath] : [];
  });
}

function readPngComment(bytes) {
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  if (bytes.length < signature.length || !bytes.subarray(0, 8).equals(signature)) {
    return undefined;
  }
  for (let offset = 8; offset + 12 <= bytes.length; ) {
    const length = bytes.readUInt32BE(offset);
    const type = bytes.subarray(offset + 4, offset + 8).toString("latin1");
    const dataStart = offset + 8;
    const dataEnd = dataStart + length;
    if (dataEnd + 4 > bytes.length) return undefined;
    if (type === "tEXt") {
      const data = bytes.subarray(dataStart, dataEnd);
      const separator = data.indexOf(0);
      if (separator >= 0 && data.subarray(0, separator).toString("latin1") === "Comment") {
        return data.subarray(separator + 1).toString("latin1");
      }
    }
    if (type === "IEND") return undefined;
    offset = dataEnd + 4;
  }
  return undefined;
}

function sourcePrefix(relativePath) {
  const directory = relativePath.split(path.sep)[0];
  if (directory === "StitchWorld") return "stitchworld";
  if (directory === "StitchWorld3") return "stitchworld3";
  if (directory === "StitchWorldExtras") return "stitchworld-extras";
  return directory.toLowerCase().replace(/[^a-z0-9]+/g, "-");
}

const patterns = walk(sourceRoot)
  .flatMap((sourcePath) => {
    const bytes = fs.readFileSync(sourcePath);
    const comment = readPngComment(bytes);
    if (!comment?.startsWith("AYAB:")) return [];
    const relativePath = path.relative(sourceRoot, sourcePath);
    const number = path.basename(sourcePath, path.extname(sourcePath));
    const prefix = sourcePrefix(relativePath);
    const stem = `${prefix}-${number}`;
    return [{ sourcePath, bytes, stem, label: `${prefix.replaceAll("-", " ")} ${number}` }];
  })
  .sort((left, right) => left.stem.localeCompare(right.stem));

fs.rmSync(outputRoot, { recursive: true, force: true });
fs.mkdirSync(outputRoot, { recursive: true });
for (const pattern of patterns) {
  fs.writeFileSync(path.join(outputRoot, `${pattern.stem}.png.bin`), pattern.bytes);
}

const sourceCommit = execFileSync("git", ["-C", sourceRoot, "rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();
const lines = [
  "/** Auto-generated by scripts/sync-ayab-annotated-patterns.mjs — do not edit. */",
  `/** Source: AllYarnsAreBeautiful/ayab-patterns@${sourceCommit} */`,
  "",
  "export const ANNOTATED_PATTERN_FILES = [",
  ...patterns.map(
    ({ stem, label }) =>
      `  { fileName: ${JSON.stringify(`${stem}.png`)}, label: ${JSON.stringify(label)} },`,
  ),
  "] as const;",
  "",
];
fs.writeFileSync(manifestPath, lines.join("\n"));

const totalBytes = patterns.reduce((sum, pattern) => sum + pattern.bytes.length, 0);
console.log(
  `Imported ${patterns.length} annotated PNGs (${totalBytes} bytes) from ${sourceCommit}.`,
);
